// Generates es/index.html from index.html + the Spanish strings in script.js,
// so search engines can index a real Spanish page. Run after editing content:
//   node tools/build-es.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://www.adrianpabonmendoza.com/";

const script = readFileSync(join(root, "script.js"), "utf8");
const block = script.match(/const translations = (\{[\s\S]*?\n\});\n/);
if (!block) throw new Error("translations object not found in script.js");
const es = vm.runInNewContext(`(${block[1]})`).es;

const escapeText = (text) => text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const escapeAttr = (text) => escapeText(text).replace(/"/g, "&quot;");
const t = (key) => {
  if (!(key in es)) throw new Error(`missing Spanish translation: ${key}`);
  return es[key];
};

let html = readFileSync(join(root, "index.html"), "utf8");

// Text content: elements marked with data-i18n hold plain text only.
html = html.replace(
  /(<([a-z0-9]+)\b[^>]*?\sdata-i18n="([^"]+)"[^>]*>)[\s\S]*?(<\/\2>)/g,
  (_, open, _tag, key, close) => `${open}${escapeText(t(key))}${close}`,
);

// Translated attributes.
for (const [marker, attr] of [
  ["data-i18n-content", "content"],
  ["data-i18n-alt", "alt"],
  ["data-i18n-aria-label", "aria-label"],
]) {
  const tagPattern = new RegExp(`<[a-z0-9]+\\b[^>]*\\s${marker}="([^"]+)"[^>]*>`, "g");
  html = html.replace(tagPattern, (tag, key) =>
    tag.replace(new RegExp(`(\\s${attr}=")[^"]*(")`), `$1${escapeAttr(t(key))}$2`),
  );
}

html = html
  .replace('<html lang="en">', '<html lang="es">')
  .replace(`<link rel="canonical" href="${SITE}" />`, `<link rel="canonical" href="${SITE}es/" />`)
  .replace(`<meta property="og:url" content="${SITE}" />`, `<meta property="og:url" content="${SITE}es/" />`)
  .replace('data-lang-option="en" data-lang-href="./"', 'data-lang-option="en" data-lang-href="../"')
  .replace('data-lang-option="es" data-lang-href="es/"', 'data-lang-option="es" data-lang-href="./"')
  // The page lives one folder down, so local assets need a ../ prefix.
  .replace(/(\s(?:href|src)=")(?=data\/|styles\.css|script\.js)/g, "$1../");

const banner = "<!-- Generated by tools/build-es.mjs from index.html. Do not edit by hand. -->\n";
mkdirSync(join(root, "es"), { recursive: true });
writeFileSync(join(root, "es", "index.html"), html.replace("<!doctype html>\n", `<!doctype html>\n${banner}`));
console.log("es/index.html written");
